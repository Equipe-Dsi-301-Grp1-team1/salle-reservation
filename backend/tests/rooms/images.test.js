const mongoose = require('mongoose');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const request = require('supertest');
const { MongoMemoryServer } = require('mongodb-memory-server');

// Dossier temporaire : les tests n'écrivent jamais dans public/uploads/rooms.
const uploadDir = fs.mkdtempSync(path.join(os.tmpdir(), 'room-photos-'));
process.env.UPLOAD_DIR = uploadDir;

const app = require('../../src/app');
const Room = require('../../src/models/Room');

jest.setTimeout(60000);

// Petits fichiers factices avec les vraies signatures (octets magiques).
const JPEG = Buffer.concat([Buffer.from([0xff, 0xd8, 0xff, 0xe0]), Buffer.alloc(32, 1)]);
const PNG = Buffer.concat([Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]), Buffer.alloc(32, 2)]);
const WEBP = Buffer.concat([Buffer.from('RIFF'), Buffer.alloc(4), Buffer.from('WEBP'), Buffer.alloc(16, 3)]);
const FAKE_IMAGE = Buffer.from('<?php echo "pas une image"; ?> contenu texte');

let mongod;
let agentId;
let room;

beforeAll(async () => {
  mongod = await MongoMemoryServer.create();
  await mongoose.connect(mongod.getUri(), { runtimeAdapters: { os } });
});

afterAll(async () => {
  await mongoose.disconnect();
  await mongod.stop();
  fs.rmSync(uploadDir, { recursive: true, force: true });
});

beforeEach(async () => {
  agentId = new mongoose.Types.ObjectId().toString();
  room = await Room.create({
    agentId,
    name: 'Salle Carthage',
    description: 'Salle de réunion à Tunis',
    address: 'Tunis',
    capacity: 50,
    pricePerHour: 100,
  });
});

afterEach(async () => {
  await Room.deleteMany({});
  for (const file of fs.readdirSync(uploadDir)) {
    fs.rmSync(path.join(uploadDir, file), { force: true });
  }
});

function apiUrl(suffix = '') {
  return '/api/agent/rooms/' + room._id + '/photos' + suffix;
}

function upload(files, asAgent = agentId) {
  const req = request(app).post(apiUrl()).set('x-test-agent-id', asAgent);
  files.forEach((f) => req.attach('photos', f.buffer, { filename: f.name, contentType: f.type }));
  return req;
}

const jpeg = (name = 'a.jpg') => ({ buffer: JPEG, name, type: 'image/jpeg' });

test('agent can upload JPEG, PNG and WebP photos', async () => {
  const res = await upload([
    jpeg(),
    { buffer: PNG, name: 'b.png', type: 'image/png' },
    { buffer: WEBP, name: 'c.webp', type: 'image/webp' },
  ]);

  expect(res.statusCode).toBe(201);
  expect(res.body.photos).toHaveLength(3);
  expect(res.body.photos[0]).toMatch(/^\/uploads\/rooms\/[a-f0-9-]{36}\.jpg$/);
  expect(res.body.photos[1]).toMatch(/\.png$/);
  expect(res.body.photos[2]).toMatch(/\.webp$/);
  expect(fs.readdirSync(uploadDir)).toHaveLength(3);

  const saved = await Room.findById(room._id);
  expect(saved.photos).toHaveLength(3);
});

test('stored file name is generated by the server, not the user file name', async () => {
  const res = await upload([jpeg('../../evil name.jpg')]);

  expect(res.statusCode).toBe(201);
  expect(res.body.photos[0]).not.toContain('evil');
  expect(fs.readdirSync(uploadDir)[0]).toMatch(/^[a-f0-9-]{36}\.jpg$/);
});

test('upload without any file is refused with a French message', async () => {
  const res = await request(app).post(apiUrl()).set('x-test-agent-id', agentId);

  expect(res.statusCode).toBe(400);
  expect(res.body.message).toBe('Aucune photo sélectionnée.');
});

test('non-image mime type is refused', async () => {
  const res = await upload([{ buffer: FAKE_IMAGE, name: 'a.pdf', type: 'application/pdf' }]);

  expect(res.statusCode).toBe(400);
  expect(res.body.message).toContain('JPEG, PNG et WebP');
  expect(fs.readdirSync(uploadDir)).toHaveLength(0);
});

test('a text file renamed .jpg is refused by the content check', async () => {
  const res = await upload([{ buffer: FAKE_IMAGE, name: 'fake.jpg', type: 'image/jpeg' }]);

  expect(res.statusCode).toBe(400);
  expect(res.body.message).toContain('n’est pas une vraie image');
  expect(fs.readdirSync(uploadDir)).toHaveLength(0);
});

test('photo over 5 MB is refused', async () => {
  const big = Buffer.concat([JPEG, Buffer.alloc(5 * 1024 * 1024 + 1)]);
  const res = await upload([{ buffer: big, name: 'big.jpg', type: 'image/jpeg' }]);

  expect(res.statusCode).toBe(400);
  expect(res.body.message).toBe('Photo trop lourde : 5 Mo maximum par fichier.');
});

test('more than 5 photos in one request is refused', async () => {
  const res = await upload([1, 2, 3, 4, 5, 6].map((i) => jpeg('p' + i + '.jpg')));

  expect(res.statusCode).toBe(400);
  expect(res.body.message).toContain('5 maximum');
  expect(fs.readdirSync(uploadDir)).toHaveLength(0);
});

test('a room cannot exceed 5 photos in total and nothing is written when refused', async () => {
  await upload([jpeg(), jpeg(), jpeg(), jpeg()]);
  const res = await upload([jpeg(), jpeg()]);

  expect(res.statusCode).toBe(400);
  expect(res.body.message).toContain('Limite atteinte');
  expect(fs.readdirSync(uploadDir)).toHaveLength(4);
  expect((await Room.findById(room._id)).photos).toHaveLength(4);
});

test('another agent cannot upload to this room', async () => {
  const other = new mongoose.Types.ObjectId().toString();
  const res = await upload([jpeg()], other);

  expect(res.statusCode).toBe(403);
  expect(fs.readdirSync(uploadDir)).toHaveLength(0);
});

test('request without agent identity is refused', async () => {
  const res = await request(app).post(apiUrl()).attach('photos', JPEG, { filename: 'a.jpg', contentType: 'image/jpeg' });

  expect(res.statusCode).toBe(401);
});

test('unknown room gives 404', async () => {
  const missing = new mongoose.Types.ObjectId().toString();
  const res = await request(app)
    .post('/api/agent/rooms/' + missing + '/photos')
    .set('x-test-agent-id', agentId)
    .attach('photos', JPEG, { filename: 'a.jpg', contentType: 'image/jpeg' });

  expect(res.statusCode).toBe(404);
});

test('agent can list and delete a photo, and the file is removed from disk', async () => {
  const created = await upload([jpeg(), jpeg()]);
  const [first, second] = created.body.photos;

  const list = await request(app).get(apiUrl()).set('x-test-agent-id', agentId);
  expect(list.body.photos).toEqual([first, second]);

  const fileName = first.split('/').pop();
  const res = await request(app).delete(apiUrl('/' + fileName)).set('x-test-agent-id', agentId);

  expect(res.statusCode).toBe(200);
  expect(res.body.photos).toEqual([second]);
  expect(fs.existsSync(path.join(uploadDir, fileName))).toBe(false);
  expect(fs.readdirSync(uploadDir)).toHaveLength(1);
});

test('delete refuses a path traversal file name', async () => {
  const res = await request(app).delete(apiUrl('/..%2F..%2Fserver.js')).set('x-test-agent-id', agentId);

  expect(res.statusCode).toBe(400);
  expect(res.body.message).toBe('Nom de photo invalide.');
});

test('another agent cannot delete a photo', async () => {
  const created = await upload([jpeg()]);
  const fileName = created.body.photos[0].split('/').pop();
  const other = new mongoose.Types.ObjectId().toString();

  const res = await request(app).delete(apiUrl('/' + fileName)).set('x-test-agent-id', other);

  expect(res.statusCode).toBe(403);
  expect(fs.readdirSync(uploadDir)).toHaveLength(1);
});

// ---------- Page EJS ----------

function pageUrl() {
  return '/agent/rooms/' + room._id + '/photos';
}

test('photos page shows the uploader and the room name', async () => {
  const res = await request(app).get(pageUrl()).query({ agentId });

  expect(res.statusCode).toBe(200);
  expect(res.text).toContain('Photos · Salle Carthage');
  expect(res.text).toContain('0 / 5 photos');
  expect(res.text).toContain('Aucune photo pour le moment.');
  expect(res.text).toContain('Envoyer les photos');
});

test('photos page without agentId is refused and another agent gets 403', async () => {
  expect((await request(app).get(pageUrl())).statusCode).toBe(401);

  const other = new mongoose.Types.ObjectId().toString();
  expect((await request(app).get(pageUrl()).query({ agentId: other })).statusCode).toBe(403);
});

test('upload from the page redirects with a message and the page shows the photo', async () => {
  const res = await request(app)
    .post(pageUrl())
    .query({ agentId })
    .attach('photos', JPEG, { filename: 'a.jpg', contentType: 'image/jpeg' });

  expect(res.statusCode).toBe(302);
  expect(decodeURIComponent(res.headers.location)).toContain('message=Photo(s) ajoutée(s).');

  const page = await request(app).get(res.headers.location);
  expect(page.text).toContain('1 / 5 photos');
  expect(page.text).toMatch(/<img src="\/uploads\/rooms\/[a-f0-9-]{36}\.jpg"/);
});

test('upload error from the page is shown on the page', async () => {
  const res = await request(app)
    .post(pageUrl())
    .query({ agentId })
    .attach('photos', FAKE_IMAGE, { filename: 'fake.jpg', contentType: 'image/jpeg' });

  expect(res.statusCode).toBe(302);

  const page = await request(app).get(res.headers.location);
  expect(page.text).toContain('n’est pas une vraie image');
});

test('delete from the page removes the photo', async () => {
  const created = await upload([jpeg()]);
  const fileName = created.body.photos[0].split('/').pop();

  const res = await request(app).post(pageUrl() + '/' + fileName + '/delete').query({ agentId });

  expect(res.statusCode).toBe(302);
  expect(decodeURIComponent(res.headers.location)).toContain('message=Photo supprimée.');
  expect((await Room.findById(room._id)).photos).toHaveLength(0);
});

test('uploaded photos are served publicly so Angular can display them', async () => {
  // Le fichier est écrit dans le dossier temporaire ; on vérifie ici que la route statique
  // /uploads est bien montée sur public/ (un fichier inexistant donne 404, pas une erreur serveur).
  const res = await request(app).get('/uploads/rooms/inexistant.jpg');
  expect(res.statusCode).toBe(404);

  const script = await request(app).get('/js/photo-preview.js');
  expect(script.statusCode).toBe(200);
});
